/** Le document de l'émetteur qui établit l'éligibilité au PEA. */
export interface PreuveEmetteur {
  document: string;
  /** Date du document : AAAA-MM-JJ, ou AAAA-MM quand le document ne porte qu'un mois. */
  date: string;
  url: string;
  /** Ce que dit le document : citation mot pour mot, sauf `paraphrase`. */
  mention: string;
  /** La mention résume le document au lieu de le citer. */
  paraphrase?: true;
}

export interface Levier {
  /** x2 : deux fois la variation ; x-1, x-2 : inverse ; x1,5 : exposition d'environ 150 %. */
  facteur: "x2" | "x-1" | "x-2" | "x1,5";
  /** Multiple recalculé chaque jour. */
  quotidien: boolean;
  /** Indicateur synthétique de risque du DIC, « 6/7 ». */
  risqueDic?: string;
  /** Période de détention recommandée par le DIC, quand elle a été relevée. */
  detentionDic?: string;
}

export interface LignePea {
  /** Mnémonique à Euronext Paris. */
  ticker: string;
  isin: string;
  nom: string;
  /** Gamme ou société de gestion, en court. */
  emetteur: string;
  categorie: CategorieId;
  /** Indice suivi, en court (ou « gestion active »). */
  indice: string;
  replication: Replication;
  /** Frais courants, % par an, d'après le DIC. */
  frais: number;
  /** Frais estimés par l'émetteur (part récente ou sans exercice complet). */
  fraisEstimes?: true;
  /** Devise de cotation à Paris. */
  devise: "EUR" | "USD";
  /** 1re cotation de cet ISIN à Paris, registre FIRDS de l'ESMA ; null si non établie. */
  coteeDepuis: string | null;
  /** 1re valeur liquidative selon l'émetteur, quand justETF concorde ; null sinon. */
  premiereVl: string | null;
  preuve: PreuveEmetteur;
  /** Sources indépendantes de l'émetteur qui concordent, relevées le 14/10/2026. */
  recoupe: ("Boursorama" | "justETF")[];
  levier?: Levier;
  /** Part que l'émetteur déclare « C/D » (capitalisation et/ou distribution). */
  partCD?: true;
  /** Ligne en dollars : la ligne en euros du même fonds. */
  equivalentEuros?: string;
  /** Réserve affichée avec la ligne. */
  reserve?: string;
  /** Précision éditoriale. */
  note?: string;
}

